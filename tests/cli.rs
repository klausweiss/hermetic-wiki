//! Scenarios from the `cli` spec, running the built binary.

mod common;

use std::path::Path;
use std::process::{Command, Output};

use common::Notes;

fn hermetic(cwd: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_hermetic"))
        .args(args)
        .current_dir(cwd)
        .output()
        .expect("runs")
}

fn stderr(o: &Output) -> String {
    String::from_utf8_lossy(&o.stderr).into_owned()
}

#[test]
fn default_output_directory() {
    let work = Notes::new(&[("notes/pages/a.md", "- a")]);
    let o = hermetic(work.path(), &["build", "notes"]);
    assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
    assert!(work.path().join("site/pages/a.html").is_file());
    assert!(stderr(&o).contains("built 1 pages into"));
}

#[test]
fn explicit_output_directory() {
    let work = Notes::new(&[("notes/pages/a.md", "- a")]);
    let o = hermetic(work.path(), &["build", "notes", "out/wiki"]);
    assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
    assert!(work.path().join("out/wiki/pages/a.html").is_file());
    assert!(!work.path().join("site").exists());
}

#[test]
fn missing_notes_directory() {
    let work = Notes::empty();
    let o = hermetic(work.path(), &["build", "nope"]);
    assert_eq!(o.status.code(), Some(1));
    assert!(
        stderr(&o).contains("error: nope is not a directory"),
        "{}",
        stderr(&o)
    );
    assert!(!work.path().join("site").exists());
}

#[test]
fn unknown_command_and_wrong_arguments() {
    let work = Notes::empty();
    for args in [&["frobnicate"][..], &["build"], &["build", "a", "b", "c"]] {
        let o = hermetic(work.path(), args);
        assert_eq!(o.status.code(), Some(2), "{args:?}");
        assert!(stderr(&o).contains("Usage:"));
        assert!(o.stdout.is_empty());
    }
}

#[test]
fn help_and_version() {
    let work = Notes::empty();
    for args in [&[][..], &["--help"]] {
        let o = hermetic(work.path(), args);
        assert_eq!(o.status.code(), Some(0));
        assert!(String::from_utf8_lossy(&o.stdout).contains("Usage:"));
    }
    let o = hermetic(work.path(), &["--version"]);
    assert_eq!(o.status.code(), Some(0));
    assert_eq!(
        String::from_utf8_lossy(&o.stdout).trim(),
        format!("hermetic {}", env!("CARGO_PKG_VERSION"))
    );
}

#[test]
fn broken_link_reported_build_succeeds() {
    let work = Notes::new(&[("notes/journals/2026-10-12.md", "- a\n- see ((missing))")]);
    let o = hermetic(work.path(), &["build", "notes"]);
    assert_eq!(o.status.code(), Some(0));
    let err = stderr(&o);
    assert!(
        err.contains("warning: journals/2026-10-12.md:2: no block has id `missing`"),
        "{err}"
    );
    assert!(err.contains("(1 warnings)"));
    assert!(work.path().join("site/journals/2026-10-12.html").is_file());
}

#[test]
fn refused_output_exits_with_one() {
    let work = Notes::new(&[("notes/pages/a.md", "- a"), ("site/report.pdf", "pdf")]);
    let o = hermetic(work.path(), &["build", "notes"]);
    assert_eq!(o.status.code(), Some(1));
    assert!(stderr(&o).contains("not empty and was not generated by hermetic"));
    assert!(work.path().join("site/report.pdf").exists());

    let o = hermetic(work.path(), &["build", "notes", "."]);
    assert_eq!(o.status.code(), Some(1));
    assert!(stderr(&o).contains("contains the notes directory"));
}

#[test]
fn building_the_current_directory_twice() {
    let work = Notes::new(&[("pages/a.md", "- a"), ("journals/2026-10-12.md", "- [[a]]")]);
    for _ in 0..2 {
        let o = hermetic(work.path(), &["build", "."]);
        assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
        assert!(stderr(&o).contains("built 2 pages"), "{}", stderr(&o));
        assert!(stderr(&o).contains("(0 warnings)"));
    }
    assert!(work.path().join("site/pages/a.html").is_file());
}
