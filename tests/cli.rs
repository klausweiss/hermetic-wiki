//! Scenarios from the `cli` spec, running the built binary.

mod common;

use std::path::Path;
use std::process::{Command, Output};

use common::Notes;

fn hermetic(cwd: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_hermetic"))
        .args(args)
        .current_dir(cwd)
        .output()
        .expect("runs")
}

fn stderr(o: &Output) -> String {
    String::from_utf8_lossy(&o.stderr).into_owned()
}

#[test]
fn default_output_directory() {
    let work = Notes::new(&[("notes/pages/a.md", "- a")]);
    let o = hermetic(work.path(), &["build", "notes"]);
    assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
    assert!(work.path().join("site/pages/a.html").is_file());
    assert!(stderr(&o).contains("built 1 pages into"));
}

#[test]
fn explicit_output_directory() {
    let work = Notes::new(&[("notes/pages/a.md", "- a")]);
    let o = hermetic(work.path(), &["build", "notes", "out/wiki"]);
    assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
    assert!(work.path().join("out/wiki/pages/a.html").is_file());
    assert!(!work.path().join("site").exists());
}

#[test]
fn site_title_defaults_to_folder_name_and_can_be_overridden() {
    let work = Notes::new(&[("my notes/pages/a.md", "- a")]);
    let o = hermetic(work.path(), &["build", "my notes"]);
    assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
    let html = std::fs::read_to_string(work.path().join("site/pages/a.html")).unwrap();
    assert!(html.contains("<title>a · my notes</title>"), "{html}");

    let o = hermetic(
        work.path(),
        &["build", "--title", "Team & Co", "my notes", "out"],
    );
    assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
    let html = std::fs::read_to_string(work.path().join("out/pages/a.html")).unwrap();
    assert!(html.contains("<title>a · Team &amp; Co</title>"), "{html}");
    assert!(html.contains(">Team &amp; Co</a>"), "{html}");
}

#[test]
fn missing_notes_directory() {
    let work = Notes::empty();
    let o = hermetic(work.path(), &["build", "nope"]);
    assert_eq!(o.status.code(), Some(1));
    assert!(
        stderr(&o).contains("error: nope is not a directory"),
        "{}",
        stderr(&o)
    );
    assert!(!work.path().join("site").exists());
}

#[test]
fn unknown_command_and_wrong_arguments() {
    let work = Notes::empty();
    for args in [
        &["frobnicate"][..],
        &["build"],
        &["build", "a", "b", "c"],
        &["build", "a", "--title"],
        &["build", "--frob", "a"],
    ] {
        let o = hermetic(work.path(), args);
        assert_eq!(o.status.code(), Some(2), "{args:?}");
        assert!(stderr(&o).contains("Usage:"));
        assert!(o.stdout.is_empty());
    }
}

#[test]
fn help_and_version() {
    let work = Notes::empty();
    for args in [&[][..], &["--help"], &["-h"]] {
        let o = hermetic(work.path(), args);
        assert_eq!(o.status.code(), Some(0));
        let out = String::from_utf8_lossy(&o.stdout);
        assert!(out.contains("Usage:"));
        assert!(out.contains("hermetic help [<topic>]"));
    }
    let o = hermetic(work.path(), &["--version"]);
    assert_eq!(o.status.code(), Some(0));
    assert_eq!(
        String::from_utf8_lossy(&o.stdout).trim(),
        format!("hermetic {}", env!("CARGO_PKG_VERSION"))
    );
}

#[test]
fn broken_link_reported_build_succeeds() {
    let work = Notes::new(&[("notes/journals/2026-10-12.md", "- a\n- see ((missing))")]);
    let o = hermetic(work.path(), &["build", "notes"]);
    assert_eq!(o.status.code(), Some(0));
    let err = stderr(&o);
    assert!(
        err.contains("warning: journals/2026-10-12.md:2: no block has id `missing`"),
        "{err}"
    );
    assert!(err.contains("(1 warnings)"));
    assert!(work.path().join("site/journals/2026-10-12.html").is_file());
}

#[test]
fn refused_output_exits_with_one() {
    let work = Notes::new(&[("notes/pages/a.md", "- a"), ("site/report.pdf", "pdf")]);
    let o = hermetic(work.path(), &["build", "notes"]);
    assert_eq!(o.status.code(), Some(1));
    assert!(stderr(&o).contains("not empty and was not generated by hermetic"));
    assert!(work.path().join("site/report.pdf").exists());

    let o = hermetic(work.path(), &["build", "notes", "."]);
    assert_eq!(o.status.code(), Some(1));
    assert!(stderr(&o).contains("contains the notes directory"));
}

#[test]
fn building_the_current_directory_twice() {
    let work = Notes::new(&[("pages/a.md", "- a"), ("journals/2026-10-12.md", "- [[a]]")]);
    for _ in 0..2 {
        let o = hermetic(work.path(), &["build", "."]);
        assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
        assert!(stderr(&o).contains("built 2 pages"), "{}", stderr(&o));
        assert!(stderr(&o).contains("(0 warnings)"));
    }
    assert!(work.path().join("site/pages/a.html").is_file());
}

fn stdout(o: &Output) -> String {
    String::from_utf8_lossy(&o.stdout).into_owned()
}

#[test]
fn full_reference() {
    let work = Notes::empty();
    let o = hermetic(work.path(), &["help"]);
    assert_eq!(o.status.code(), Some(0), "{}", stderr(&o));
    let out = stdout(&o);
    assert_eq!(out, hermetic::help::reference());
    let headings = ["COMMANDS", "NOTES LAYOUT", "SYNTAX", "PAGES AND REFERENCES"];
    let at: Vec<usize> = headings
        .iter()
        .map(|h| {
            out.find(&format!("\n{h}\n"))
                .unwrap_or_else(|| panic!("{h}"))
        })
        .collect();
    assert!(at.is_sorted(), "{at:?}");

    let usage = stdout(&hermetic(work.path(), &["--help"]));
    assert!(usage.len() < out.len());
}

#[test]
fn single_topics() {
    let work = Notes::empty();
    for name in hermetic::help::TOPICS {
        let o = hermetic(work.path(), &["help", name]);
        assert_eq!(o.status.code(), Some(0), "{name}");
        assert_eq!(stdout(&o), hermetic::help::topic(name).unwrap());
    }
    let layout = stdout(&hermetic(work.path(), &["help", "layout"]));
    assert!(layout.starts_with("NOTES LAYOUT\n"));
    assert!(layout.contains("journals/YYYY-MM-DD.md"));
    assert!(layout.contains("index.md"));
    assert!(!layout.contains("\nSYNTAX\n"));
    let syntax = stdout(&hermetic(work.path(), &["help", "syntax"]));
    for example in [
        "[[name]]",
        "#name",
        "#[[multi word]]",
        "((id))",
        "key:: value",
        "id::",
        "TODO",
    ] {
        assert!(syntax.contains(example), "{example}");
    }
    assert!(!syntax.contains("\nCOMMANDS\n"));
    // Editing is described: same machine only, saved to the note files.
    let commands = stdout(&hermetic(work.path(), &["help", "commands"]));
    for phrase in [
        "same machine",
        "saved to the note files",
        "can never edit",
        ".trash/",
    ] {
        assert!(commands.contains(phrase), "{phrase}");
    }
}

#[test]
fn unknown_help_topic() {
    let work = Notes::empty();
    let o = hermetic(work.path(), &["help", "frobnicate"]);
    assert_eq!(o.status.code(), Some(2));
    assert!(o.stdout.is_empty());
    let err = stderr(&o);
    assert!(err.contains("unknown help topic `frobnicate`"), "{err}");
    for name in hermetic::help::TOPICS {
        assert!(err.contains(name), "{name}");
    }

    let o = hermetic(work.path(), &["help", "syntax", "layout"]);
    assert_eq!(o.status.code(), Some(2));
    assert!(o.stdout.is_empty());
    assert!(stderr(&o).contains("Usage:"));
}
